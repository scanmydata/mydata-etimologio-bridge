// --- Payments ---------------------------------------------------------------

// Map a raw DB row to a decrypted, app-friendly array
function payment_row(array $r): array {
    return [
        'id'            => (int)$r['id'],
        'account_vat'   => $r['account_vat'],
        'customer_vat'  => $r['customer_vat'],
        'customer_code' => $r['customer_code'],
        'customer_name' => dec($r['customer_name']),
        'amount'        => round(dec_num($r['amount']), 2),
        'method'        => (int)$r['method'],
        'pay_date'      => $r['pay_date'],
        'mark'          => $r['mark'],
        'notes'         => dec($r['notes']),
        'created_at'    => $r['created_at'],
    ];
}

function payments_list(string $accountVat, string $customerVat = '', string $from = '', string $to = ''): array {
    $sql = "SELECT * FROM payments WHERE account_vat = :acc";
    $args = [':acc' => $accountVat];
    if ($customerVat !== '') { $sql .= " AND customer_vat = :cv"; $args[':cv'] = $customerVat; }
    if ($from !== '')        { $sql .= " AND pay_date >= :from"; $args[':from'] = $from; }
    if ($to !== '')          { $sql .= " AND pay_date <= :to";   $args[':to']   = $to; }
    $sql .= " ORDER BY pay_date DESC, id DESC";
    $st = localdb()->prepare($sql);
    $st->execute($args);
    return array_map('payment_row', $st->fetchAll());
}

function payment_add(string $accountVat, array $d): int {
    return db_insert("
        INSERT INTO payments (account_vat, customer_vat, customer_code, customer_name, amount, method, pay_date, mark, notes)
        VALUES (:acc, :cv, :cc, :cn, :amt, :m, :dt, :mk, :nt)
    ", [
        ':acc' => $accountVat,
        ':cv'  => trim($d['customer_vat']  ?? ''),
        ':cc'  => trim($d['customer_code'] ?? ''),
        ':cn'  => enc(trim($d['customer_name'] ?? '')),
        ':amt' => enc_num(round((float)($d['amount'] ?? 0), 2)),
        ':m'   => (int)($d['method'] ?? 3),
        ':dt'  => trim($d['pay_date'] ?? date('Y-m-d')),
        ':mk'  => trim($d['mark'] ?? ''),
        ':nt'  => enc(trim($d['notes'] ?? '')),
    ]);
}

function payment_delete(string $accountVat, int $id): bool {
    $st = localdb()->prepare("DELETE FROM payments WHERE account_vat = :acc AND id = :id");
    $st->execute([':acc' => $accountVat, ':id' => $id]);
    return $st->rowCount() > 0;
}

function payments_total(string $accountVat, string $customerVat = ''): float {
    $sum = 0.0;
    foreach (payments_list($accountVat, $customerVat) as $p) $sum += $p['amount'];
    return round($sum, 2);
}

// --- Snapshot cache ---------------------------------------------------------

function cache_get(string $accountVat, string $kind): ?array {
    $st = localdb()->prepare("SELECT payload, hash, synced_at FROM app_cache WHERE account_vat = :a AND kind = :k");
    $st->execute([':a' => $accountVat, ':k' => $kind]);
    $r = $st->fetch();
    if (!$r) return null;
    $rows = json_decode(dec($r['payload']), true);
    return ['rows' => is_array($rows) ? $rows : [], 'hash' => $r['hash'], 'synced_at' => $r['synced_at']];
}

function cache_set(string $accountVat, string $kind, array $rows): string {
    $json = json_encode($rows, JSON_UNESCAPED_UNICODE);
    $hash = md5($json);
    $now = db_now_sql();
    $st = localdb()->prepare("
        INSERT INTO app_cache (account_vat, kind, payload, hash, synced_at)
        VALUES (:a, :k, :p, :h, $now)
        ON CONFLICT(account_vat, kind) DO UPDATE SET
            payload = excluded.payload, hash = excluded.hash, synced_at = excluded.synced_at
    ");
    $st->execute([':a' => $accountVat, ':k' => $kind, ':p' => enc($json), ':h' => $hash]);
    return $hash;
}

// --- Customer meta (opening balance + notes) --------------------------------

function customer_meta_get(string $accountVat, string $customerVat): array {
    $st = localdb()->prepare("SELECT * FROM customer_meta WHERE account_vat = :acc AND customer_vat = :cv");
    $st->execute([':acc' => $accountVat, ':cv' => $customerVat]);
    $r = $st->fetch();
    if (!$r) return ['opening_balance' => 0.0, 'notes' => '', 'customer_name' => ''];
    return [
        'customer_name'   => dec($r['customer_name']),
        'opening_balance' => round(dec_num($r['opening_balance']), 2),
        'notes'           => dec($r['notes']),
        'updated_at'      => $r['updated_at'],
    ];
}

function customer_meta_set(string $accountVat, string $customerVat, array $d): void {
    $now = db_now_sql();
    $st = localdb()->prepare("
        INSERT INTO customer_meta (account_vat, customer_vat, customer_name, opening_balance, notes, updated_at)
        VALUES (:acc, :cv, :cn, :ob, :nt, $now)
        ON CONFLICT(account_vat, customer_vat) DO UPDATE SET
            customer_name   = excluded.customer_name,
            opening_balance = excluded.opening_balance,
            notes           = excluded.notes,
            updated_at      = $now
    ");
    $st->execute([
        ':acc' => $accountVat,
        ':cv'  => $customerVat,
        ':cn'  => enc(trim($d['customer_name'] ?? '')),
        ':ob'  => enc_num(round((float)($d['opening_balance'] ?? 0), 2)),
        ':nt'  => enc(trim($d['notes'] ?? '')),
    ]);
}

// --- Per-customer delivery-note settings (branch + delivery address) --------
// Stored as encrypted JSON in customer_meta.deliv_meta so repeat delivery notes
// to the same customer prefill the last-used branch/address. Touches ONLY the
// deliv_meta column (does not disturb opening_balance/notes).

function customer_deliv_get(string $accountVat, string $customerVat): array {
    $st = localdb()->prepare("SELECT deliv_meta FROM customer_meta WHERE account_vat = :acc AND customer_vat = :cv");
    $st->execute([':acc' => $accountVat, ':cv' => $customerVat]);
    $raw = $st->fetchColumn();
    if ($raw === false || $raw === null || $raw === '') return [];
    $json = dec($raw);
    $d = $json !== '' ? json_decode($json, true) : null;
    return is_array($d) ? $d : [];
}

function customer_deliv_set(string $accountVat, string $customerVat, array $d): void {
    $now = db_now_sql();
    $st = localdb()->prepare("
        INSERT INTO customer_meta (account_vat, customer_vat, deliv_meta, updated_at)
        VALUES (:acc, :cv, :dm, $now)
        ON CONFLICT(account_vat, customer_vat) DO UPDATE SET
            deliv_meta = excluded.deliv_meta,
            updated_at = $now
    ");
    $st->execute([
        ':acc' => $accountVat,
        ':cv'  => $customerVat,
        ':dm'  => enc(json_encode($d, JSON_UNESCAPED_UNICODE)),
    ]);
}

// --- Scheduled issuance jobs -------------------------------------------------

function sched_row(array $r): array {
    $result = $r['last_result'] !== '' ? json_decode(dec($r['last_result']), true) : null;
    return [
        'id'          => (int)$r['id'],
        'account_vat' => $r['account_vat'],
        'user_id'     => (int)$r['user_id'],
        'title'       => $r['title'] !== '' ? dec($r['title']) : '',
        'kind'        => $r['kind'],
        'run_at'      => $r['run_at'],
        'recurrence'  => $r['recurrence'],
        'status'      => $r['status'],
        'attempts'    => (int)$r['attempts'],
        'last_run_at' => $r['last_run_at'],
        'last_result' => is_array($result) ? $result : null,
        'created_at'  => $r['created_at'],
    ];
}

function sched_add(string $accountVat, int $userId, array $d): int {
    return db_insert("
        INSERT INTO scheduled_jobs (account_vat, user_id, title, kind, payload, run_at, recurrence, status)
        VALUES (:acc, :uid, :title, :kind, :payload, :run_at, :rec, 'pending')
    ", [
        ':acc'     => $accountVat,
        ':uid'     => $userId,
        ':title'   => enc(trim((string)($d['title'] ?? ''))),
        ':kind'    => trim((string)($d['kind'] ?? 'invoice')),
        ':payload' => enc(json_encode($d['payload'] ?? [], JSON_UNESCAPED_UNICODE)),
        ':run_at'  => trim((string)($d['run_at'] ?? '')),
        ':rec'     => in_array($d['recurrence'] ?? 'none', ['none','daily','weekly','monthly'], true) ? $d['recurrence'] : 'none',
    ]);
}

// List jobs for the UI. Master (accountVat === '') sees every account's jobs.
function sched_list(string $accountVat = '', int $limit = 500): array {
    if ($accountVat === '') {
        $st = localdb()->prepare("SELECT * FROM scheduled_jobs ORDER BY (status='pending') DESC, run_at DESC LIMIT :l");
        $st->bindValue(':l', $limit, \PDO::PARAM_INT);
    } else {
        $st = localdb()->prepare("SELECT * FROM scheduled_jobs WHERE account_vat = :acc ORDER BY (status='pending') DESC, run_at DESC LIMIT :l");
        $st->bindValue(':acc', $accountVat);
        $st->bindValue(':l', $limit, \PDO::PARAM_INT);
    }
    $st->execute();
    return array_map('sched_row', $st->fetchAll());
}

// Full row incl. decrypted payload — used by the runner only.
function sched_get_full(int $id): ?array {
    $st = localdb()->prepare("SELECT * FROM scheduled_jobs WHERE id = :id");
    $st->execute([':id' => $id]);
    $r = $st->fetch();
    if (!$r) return null;
    $out = sched_row($r);
    $out['payload'] = $r['payload'] !== '' ? (json_decode(dec($r['payload']), true) ?: []) : [];
    return $out;
}

// Due jobs across all accounts (runner). $now = 'Y-m-d H:i:s'.
function sched_due(string $now, int $limit = 100): array {
    $st = localdb()->prepare("
        SELECT * FROM scheduled_jobs
        WHERE status = 'pending' AND run_at <= :now
        ORDER BY run_at ASC LIMIT :l
    ");
    $st->bindValue(':now', $now);
    $st->bindValue(':l', $limit, \PDO::PARAM_INT);
    $st->execute();
    return array_map(function ($r) {
        $out = sched_row($r);
        $out['payload'] = $r['payload'] !== '' ? (json_decode(dec($r['payload']), true) ?: []) : [];
        return $out;
    }, $st->fetchAll());
}

function sched_set_status(int $id, string $status): void {
    $st = localdb()->prepare("UPDATE scheduled_jobs SET status = :s WHERE id = :id");
    $st->execute([':s' => $status, ':id' => $id]);
}

// Record a run outcome. If $nextRunAt is given the job is re-queued (recurrence);
// otherwise it lands on the terminal $status ('done' | 'failed').
function sched_record_result(int $id, string $status, array $result, ?string $nextRunAt = null): void {
    if ($nextRunAt !== null) {
        $st = localdb()->prepare("
            UPDATE scheduled_jobs
               SET status='pending', attempts = attempts + 1, last_run_at = :lr,
                   last_result = :res, run_at = :next
             WHERE id = :id
        ");
        $st->execute([
            ':lr' => date('Y-m-d H:i:s'), ':res' => enc(json_encode($result, JSON_UNESCAPED_UNICODE)),
            ':next' => $nextRunAt, ':id' => $id,
        ]);
        return;
    }
    $st = localdb()->prepare("
        UPDATE scheduled_jobs
           SET status = :s, attempts = attempts + 1, last_run_at = :lr, last_result = :res
         WHERE id = :id
    ");
    $st->execute([
        ':s' => $status, ':lr' => date('Y-m-d H:i:s'),
        ':res' => enc(json_encode($result, JSON_UNESCAPED_UNICODE)), ':id' => $id,
    ]);
}

// Cancel a pending job (scoped by account for safety; master passes '' to skip scope).
function sched_cancel(int $id, string $accountVat = ''): bool {
    if ($accountVat === '') {
        $st = localdb()->prepare("UPDATE scheduled_jobs SET status='cancelled' WHERE id = :id AND status='pending'");
        $st->execute([':id' => $id]);
    } else {
        $st = localdb()->prepare("UPDATE scheduled_jobs SET status='cancelled' WHERE id = :id AND account_vat = :acc AND status='pending'");
        $st->execute([':id' => $id, ':acc' => $accountVat]);
    }
    return $st->rowCount() > 0;
}

// Compute the next run for a recurring job from a base 'Y-m-d H:i:s'. Returns
// null for non-recurring jobs.
function sched_next_run(string $baseRunAt, string $recurrence): ?string {
    if ($recurrence === 'none' || $recurrence === '') return null;
    $ts = strtotime($baseRunAt);
    if ($ts === false) return null;
    $map = ['daily' => '+1 day', 'weekly' => '+1 week', 'monthly' => '+1 month'];
    if (!isset($map[$recurrence])) return null;
    // Advance until strictly in the future so a long-overdue job doesn't fire in a loop.
    $next = $ts;
    $guard = 0;
    do { $next = strtotime($map[$recurrence], $next); $guard++; }
    while ($next !== false && $next <= time() && $guard < 4000);
    return $next ? date('Y-m-d H:i:s', $next) : null;
}

