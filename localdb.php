<?php
// ============================================================================
// Local data store (SQLite) — for data e-timologio does NOT keep.
// ----------------------------------------------------------------------------
// Multi-tenant: every row is scoped by `account_vat` (the issuing company) so a
// single database file can serve many e-timologio accounts, each with many
// customers. Payments here are LOCAL ONLY — they are never sent to AADE.
//
// Sensitive content (customer name, notes, amounts) is encrypted at rest via
// crypto.php. Identifier/index fields (VATs, dates, method, mark) stay plain so
// the app can still filter and scope. Aggregation is done in PHP after decrypt.
// ============================================================================

require_once __DIR__ . '/crypto.php';

// Which SQL engine backs this instance: 'sqlite' (local/offline) or 'pgsql'
// (central VPS via Coolify). Selected by the DB_DSN config (see below).
function db_dialect(?\PDO $pdo = null): string {
    static $d = null;
    if ($d !== null) return $d;
    $p = $pdo ?? localdb();
    $d = ($p->getAttribute(\PDO::ATTR_DRIVER_NAME) === 'pgsql') ? 'pgsql' : 'sqlite';
    return $d;
}

// Portable "now as 'Y-m-d H:i:s'" SQL expression, used inside DML (INSERT/UPDATE).
function db_now_sql(): string {
    return db_dialect() === 'pgsql'
        ? "to_char((now() AT TIME ZONE 'UTC'),'YYYY-MM-DD HH24:MI:SS')"
        : "datetime('now')";
}

// Run an INSERT and return the new id, portably. SQLite uses lastInsertId();
// Postgres appends RETURNING id (identity columns don't expose lastInsertId).
function db_insert(string $sql, array $params): int {
    $pdo = localdb();
    if (db_dialect() === 'pgsql') {
        $st = $pdo->prepare(rtrim($sql) . "\n        RETURNING id");
        $st->execute($params);
        return (int)$st->fetchColumn();
    }
    $st = $pdo->prepare($sql);
    $st->execute($params);
    return (int)$pdo->lastInsertId();
}

function localdb(): \PDO {
    static $pdo = null;
    if ($pdo !== null) return $pdo;

    // Local/offline default = SQLite file; central server sets DB_DSN to a
    // pgsql DSN (+ DB_USER/DB_PASS). One data layer serves both.
    $dsn  = (defined('DB_DSN') && DB_DSN !== '') ? DB_DSN : ('sqlite:' . LOCAL_DB);
    $user = (defined('DB_USER') && DB_USER !== '') ? DB_USER : null;
    $pass = (defined('DB_PASS') && DB_PASS !== '') ? DB_PASS : null;
    $pdo = new \PDO($dsn, $user, $pass);
    $pdo->setAttribute(\PDO::ATTR_ERRMODE, \PDO::ERRMODE_EXCEPTION);
    $pdo->setAttribute(\PDO::ATTR_DEFAULT_FETCH_MODE, \PDO::FETCH_ASSOC);
    $isPg = $pdo->getAttribute(\PDO::ATTR_DRIVER_NAME) === 'pgsql';
    if (!$isPg) $pdo->exec('PRAGMA journal_mode = WAL');

    // DDL translator: the schema below is written in SQLite syntax; for Postgres
    // we swap the two non-portable tokens (identity PK + timestamp default).
    $tr = static function (string $sql) use ($pdo, $isPg) {
        if ($isPg) {
            $sql = str_replace('INTEGER PRIMARY KEY AUTOINCREMENT',
                               'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', $sql);
            $sql = str_replace("(datetime('now'))",
                               "(to_char((now() AT TIME ZONE 'UTC'),'YYYY-MM-DD HH24:MI:SS'))", $sql);
        }
        return $pdo->exec($sql);
    };

    // Encrypted fields are stored as TEXT (ciphertext). Index/date fields plain.
    $tr("
        CREATE TABLE IF NOT EXISTS payments (
            id            INTEGER PRIMARY KEY AUTOINCREMENT,
            account_vat   TEXT NOT NULL,
            customer_vat  TEXT NOT NULL DEFAULT '',
            customer_code TEXT NOT NULL DEFAULT '',
            customer_name TEXT NOT NULL DEFAULT '',   -- encrypted
            amount        TEXT NOT NULL DEFAULT '',    -- encrypted
            method        INTEGER NOT NULL DEFAULT 3,
            pay_date      TEXT NOT NULL,
            mark          TEXT NOT NULL DEFAULT '',
            notes         TEXT NOT NULL DEFAULT '',    -- encrypted
            created_at    TEXT NOT NULL DEFAULT (datetime('now'))
        )
    ");
    $tr("CREATE INDEX IF NOT EXISTS idx_pay_acc_cust ON payments(account_vat, customer_vat)");

    // Encrypted snapshot cache of AADE data (customers/products/invoices) so the
    // UI can render instantly and only re-fetch/compare in the background.
    $tr("
        CREATE TABLE IF NOT EXISTS app_cache (
            account_vat TEXT NOT NULL,
            kind        TEXT NOT NULL,
            payload     TEXT NOT NULL DEFAULT '',  -- encrypted JSON snapshot
            hash        TEXT NOT NULL DEFAULT '',
            synced_at   TEXT NOT NULL DEFAULT (datetime('now')),
            PRIMARY KEY (account_vat, kind)
        )
    ");

    $tr("
        CREATE TABLE IF NOT EXISTS customer_meta (
            account_vat     TEXT NOT NULL,
            customer_vat    TEXT NOT NULL,
            customer_name   TEXT NOT NULL DEFAULT '',  -- encrypted
            opening_balance TEXT NOT NULL DEFAULT '',  -- encrypted
            notes           TEXT NOT NULL DEFAULT '',  -- encrypted
            deliv_meta      TEXT NOT NULL DEFAULT '',  -- encrypted JSON: branch + delivery address
            updated_at      TEXT NOT NULL DEFAULT (datetime('now')),
            PRIMARY KEY (account_vat, customer_vat)
        )
    ");
    // Upgrade path for DBs created before deliv_meta existed.
    try { $tr("ALTER TABLE customer_meta ADD COLUMN deliv_meta TEXT NOT NULL DEFAULT ''"); } catch (\Throwable $e) {}

    // --- Auth: application users (master admin + business accounts) ----------
    // email is the login identifier (kept plaintext so it can be queried).
    // role: 'master' | 'business'.  status: 'pending' | 'active' | 'disabled'.
    $tr("
        CREATE TABLE IF NOT EXISTS users (
            id            INTEGER PRIMARY KEY AUTOINCREMENT,
            email         TEXT NOT NULL UNIQUE,
            password_hash TEXT NOT NULL,
            role          TEXT NOT NULL DEFAULT 'business',
            status        TEXT NOT NULL DEFAULT 'pending',
            business_name TEXT NOT NULL DEFAULT '',
            reset_token   TEXT NOT NULL DEFAULT '',
            reset_expires INTEGER NOT NULL DEFAULT 0,
            totp_secret   TEXT NOT NULL DEFAULT '',   -- encrypted Base32 secret
            totp_enabled  INTEGER NOT NULL DEFAULT 0,
            invited_by    INTEGER NOT NULL DEFAULT 0,
            created_at    TEXT NOT NULL DEFAULT (datetime('now'))
        )
    ");
    // Upgrade path for DBs created before 2FA / invitations / notify-prefs existed.
    foreach ([
        "ALTER TABLE users ADD COLUMN totp_secret TEXT NOT NULL DEFAULT ''",
        "ALTER TABLE users ADD COLUMN totp_enabled INTEGER NOT NULL DEFAULT 0",
        "ALTER TABLE users ADD COLUMN invited_by INTEGER NOT NULL DEFAULT 0",
        "ALTER TABLE users ADD COLUMN notify_prefs TEXT NOT NULL DEFAULT ''",   // encrypted JSON
    ] as $ddl) { try { $tr($ddl); } catch (\Throwable $e) {} }

    // AADE (e-timologio) credentials per business user. vat/label plaintext (used
    // for scoping local data + cookie file + account switching); the e-timologio
    // username and subscription key are encrypted at rest.
    $tr("
        CREATE TABLE IF NOT EXISTS aade_accounts (
            id            INTEGER PRIMARY KEY AUTOINCREMENT,
            user_id       INTEGER NOT NULL,
            vat           TEXT NOT NULL,
            label         TEXT NOT NULL DEFAULT '',
            username_enc  TEXT NOT NULL DEFAULT '',   -- encrypted
            subkey_enc    TEXT NOT NULL DEFAULT '',   -- encrypted
            created_at    TEXT NOT NULL DEFAULT (datetime('now'))
        )
    ");
    $tr("CREATE INDEX IF NOT EXISTS idx_acc_user ON aade_accounts(user_id)");

    // --- Scheduled issuance (χρονοπρογραμματισμός) ---------------------------
    // A persistent job store: each row is a παραστατικό (single or bulk) queued
    // to be issued automatically at `run_at`. The `payload` is the ENCRYPTED set
    // of request params the runner replays against the bridge (see scheduler.php).
    // run_at / next_run_at are 'Y-m-d H:i:s' in Europe/Athens local time.
    // status: 'pending' | 'running' | 'done' | 'failed' | 'cancelled'.
    // recurrence: 'none' | 'daily' | 'weekly' | 'monthly'.
    $tr("
        CREATE TABLE IF NOT EXISTS scheduled_jobs (
            id           INTEGER PRIMARY KEY AUTOINCREMENT,
            account_vat  TEXT NOT NULL,
            user_id      INTEGER NOT NULL,
            title        TEXT NOT NULL DEFAULT '',   -- encrypted (human label)
            kind         TEXT NOT NULL DEFAULT 'invoice',
            payload      TEXT NOT NULL DEFAULT '',    -- encrypted JSON of request params
            run_at       TEXT NOT NULL,
            recurrence   TEXT NOT NULL DEFAULT 'none',
            status       TEXT NOT NULL DEFAULT 'pending',
            attempts     INTEGER NOT NULL DEFAULT 0,
            last_run_at  TEXT NOT NULL DEFAULT '',
            last_result  TEXT NOT NULL DEFAULT '',    -- encrypted JSON (mark/aa or error)
            created_at   TEXT NOT NULL DEFAULT (datetime('now'))
        )
    ");
    $tr("CREATE INDEX IF NOT EXISTS idx_sched_due ON scheduled_jobs(status, run_at)");
    $tr("CREATE INDEX IF NOT EXISTS idx_sched_acc ON scheduled_jobs(account_vat)");

    // --- Issuance notifications (ειδοποιήσεις λογιστή/admin) -----------------
    // One row per successfully issued παραστατικό (ΜΑΡΚ obtained), EXCLUDING
    // δελτία αποστολής (9.x). Surfaced to the master admin (all accounts) and to
    // the business itself (own account). Buyer name / amount encrypted at rest.
    $tr("
        CREATE TABLE IF NOT EXISTS issue_notifications (
            id            INTEGER PRIMARY KEY AUTOINCREMENT,
            account_vat   TEXT NOT NULL,
            actor_user_id INTEGER NOT NULL DEFAULT 0,
            actor_email   TEXT NOT NULL DEFAULT '',
            actor_name    TEXT NOT NULL DEFAULT '',
            doc_type      TEXT NOT NULL DEFAULT '',
            doc_label     TEXT NOT NULL DEFAULT '',
            series        TEXT NOT NULL DEFAULT '',
            aa            TEXT NOT NULL DEFAULT '',
            mark          TEXT NOT NULL DEFAULT '',
            buyer_vat     TEXT NOT NULL DEFAULT '',
            buyer_name    TEXT NOT NULL DEFAULT '',   -- encrypted
            amount_total  TEXT NOT NULL DEFAULT '',    -- encrypted
            source        TEXT NOT NULL DEFAULT 'manual', -- 'manual' | 'scheduled' | 'bulk'
            is_read       INTEGER NOT NULL DEFAULT 0,
            created_at    TEXT NOT NULL DEFAULT (datetime('now'))
        )
    ");
    $tr("CREATE INDEX IF NOT EXISTS idx_notif_acc ON issue_notifications(account_vat, is_read)");

    return $pdo;
}

// --- Auth: users ------------------------------------------------------------

function user_public(array $r): array {
    return [
        'id'            => (int)$r['id'],
        'email'         => $r['email'],
        'role'          => $r['role'],
        'status'        => $r['status'],
        'business_name' => $r['business_name'],
        'totp_enabled'  => (int)($r['totp_enabled'] ?? 0),
        'created_at'    => $r['created_at'] ?? '',
    ];
}

function user_by_email(string $email): ?array {
    $st = localdb()->prepare("SELECT * FROM users WHERE email = :e");
    $st->execute([':e' => strtolower(trim($email))]);
    return $st->fetch() ?: null;
}

function user_by_id(int $id): ?array {
    $st = localdb()->prepare("SELECT * FROM users WHERE id = :id");
    $st->execute([':id' => $id]);
    return $st->fetch() ?: null;
}

function user_create(string $email, string $passwordHash, string $role, string $status, string $businessName): int {
    return db_insert("
        INSERT INTO users (email, password_hash, role, status, business_name)
        VALUES (:e, :p, :r, :s, :b)
    ", [
        ':e' => strtolower(trim($email)), ':p' => $passwordHash,
        ':r' => $role, ':s' => $status, ':b' => trim($businessName),
    ]);
}

function user_update(int $id, array $fields): void {
    $allowed = ['password_hash', 'role', 'status', 'business_name', 'reset_token', 'reset_expires', 'email', 'totp_secret', 'totp_enabled', 'invited_by'];
    $sets = []; $args = [':id' => $id];
    foreach ($fields as $k => $v) {
        if (!in_array($k, $allowed, true)) continue;
        $sets[] = "$k = :$k"; $args[":$k"] = $v;
    }
    if (!$sets) return;
    $st = localdb()->prepare("UPDATE users SET " . implode(', ', $sets) . " WHERE id = :id");
    $st->execute($args);
}

function users_all(): array {
    $rows = localdb()->query("SELECT * FROM users ORDER BY (role='master') DESC, created_at DESC")->fetchAll();
    return array_map('user_public', $rows);
}

function users_count_master(): int {
    return (int)localdb()->query("SELECT COUNT(*) FROM users WHERE role='master'")->fetchColumn();
}

// --- Auth: AADE accounts ----------------------------------------------------

function account_row(array $r): array {
    return [
        'id'       => (int)$r['id'],
        'user_id'  => (int)$r['user_id'],
        'vat'      => $r['vat'],
        'label'    => $r['label'],
        'username' => dec($r['username_enc']),
        'subkey'   => dec($r['subkey_enc']),
        'created_at' => $r['created_at'] ?? '',
    ];
}

function accounts_for_user(int $userId): array {
    $st = localdb()->prepare("SELECT * FROM aade_accounts WHERE user_id = :u ORDER BY id ASC");
    $st->execute([':u' => $userId]);
    return array_map('account_row', $st->fetchAll());
}

// All linked AADE businesses (across every user) — for the master admin's business list.
// The subkey is intentionally omitted (never surfaced to the UI list).
function accounts_all(): array {
    $rows = localdb()->query(
        "SELECT a.*, u.email AS owner_email FROM aade_accounts a LEFT JOIN users u ON u.id = a.user_id ORDER BY a.id ASC"
    )->fetchAll();
    return array_map(function ($r) {
        $a = account_row($r);
        unset($a['subkey']);
        $a['owner_email'] = $r['owner_email'] ?? '';
        return $a;
    }, $rows);
}

// All linked AADE businesses WITH credentials — for internal account resolution
// by staff (accountant/admin) acting on any company. NEVER expose to the UI.
function accounts_all_full(): array {
    $rows = localdb()->query("SELECT * FROM aade_accounts ORDER BY id ASC")->fetchAll();
    return array_map('account_row', $rows);
}

function account_by_vat(string $vat): ?array {
    $vat = preg_replace('/\D/', '', $vat);
    if ($vat === '') return null;
    $st = localdb()->prepare("SELECT * FROM aade_accounts WHERE vat = :v ORDER BY id ASC LIMIT 1");
    $st->execute([':v' => $vat]);
    $r = $st->fetch();
    return $r ? account_row($r) : null;
}

function account_get(int $id): ?array {
    $st = localdb()->prepare("SELECT * FROM aade_accounts WHERE id = :id");
    $st->execute([':id' => $id]);
    $r = $st->fetch();
    return $r ? account_row($r) : null;
}

