def percent(value: float) -> str:
    """Ίδιος κανόνας, βολικότερη υπογραφή για το σύνολο δεδομένων."""
    if float(value).is_integer():
        return _percent(int(value))
    whole, frac = str(value).split(".")
    return _percent(int(whole), frac)


def fmt_money(euros: int, cents: int) -> str:
    """Το ποσό όπως το ΓΡΑΦΕΙ η εφαρμογή (η εκφώνηση είναι η `money`)."""
    return "{:,}".format(euros).replace(",", ".") + ",{:02d}".format(cents)


def say_size(mb: float) -> str:
    """«444,4 MB» → «τετρακόσια σαράντα τέσσερα κόμμα τέσσερα μεγκαμπάιτ»."""
    whole = int(mb)
    frac = round((mb - whole) * 10)
    head = number(whole)
    if frac:
        head += " κόμμα " + ONES[frac]
    return head + " μεγκαμπάιτ"


