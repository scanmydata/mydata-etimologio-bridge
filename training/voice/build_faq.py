INSTRUCTION = (
    "Είσαι ο ψηφιακός βοηθός του e-Τιμολόγιο. Ο χρήστης ρωτά πώς δουλεύει η "
    "εφαρμογή. Απάντησε ΜΟΝΟ με ένα JSON αντικείμενο με κλειδιά say (σύντομη "
    "απάντηση, δύο-τρεις προτάσεις, θα ακουστεί) και προαιρετικά navigate "
    "(η ενότητα που πρέπει να ανοίξει). Ο βοηθός ΔΕΝ εκδίδει ποτέ οριστικά."
)

rows: list[dict[str, str]] = []


def add(questions: tuple[str, ...] | list[str], say: str, navigate: str = "") -> None:
    """Πολλές διατυπώσεις, μία απάντηση.

    Οι διατυπώσεις δεν είναι διακοσμητικές: ο λογιστής ρωτά «πώς κόβω
    πιστωτικό», «πώς ακυρώνω τιμολόγιο» και «θέλω να σβήσω ένα παραστατικό» —
    τρεις προτάσεις χωρίς κοινή λέξη, για την ίδια δουλειά.
    """
    action: dict[str, str] = {"say": say}
    if navigate:
        action["navigate"] = navigate
    payload = json.dumps(action, ensure_ascii=False)
    for question in questions:
        rows.append({"instruction": INSTRUCTION, "input": question,
                     "output": payload})


