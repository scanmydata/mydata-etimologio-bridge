"""Σύνολο εκπαίδευσης «πώς δουλεύει η εφαρμογή» — ο βοηθός που ΞΕΡΕΙ.

Ο δρομολογητής (`build_intents.py`) απαντά στο **τι να κάνω**: «άνοιξε τα
πρόχειρα» → πάει στα πρόχειρα. Δεν απαντά όμως στο **πώς γίνεται**: «πώς
ακυρώνω τιμολόγιο;», «γιατί λέει αναμονή ενώ το κατέβασα;», «πού βάζω το κλειδί
της ΑΑΔΕ;». Σήμερα ο βοηθός λέει «δεν το κατάλαβα» — και ο λογιστής ανοίγει το
εγχειρίδιο PDF.

Αυτό το αρχείο γεννά ζευγάρια **ερώτηση → σύντομη απάντηση + πλοήγηση**. Η
απάντηση ακούγεται (Piper), οπότε είναι δύο-τρεις προτάσεις, όχι παράγραφος.

ΙΔΙΟ ΣΥΜΒΟΛΑΙΟ με τον δρομολογητή: η έξοδος είναι JSON με κλειδιά του `Reply`
(`say`, `navigate`). Έτσι το ίδιο LoRA μαθαίνει και τις δύο δουλειές και ο
επικυρωτής της εφαρμογής δεν χρειάζεται αλλαγή.

Το περιεχόμενο είναι αντιγραμμένο από τα ίδια τα εγχειρίδια
(`desktop/src/timologio/gui/manual.py`, `etimologio/help.py`, `MANUAL` στο
`app.php`) — όχι από μνήμη. Όταν αλλάζει η εφαρμογή, αλλάζει και εδώ.
"""

