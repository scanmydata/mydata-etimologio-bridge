# --- Θόρυβος αναγνώρισης -------------------------------------------------------
# Η ερώτηση φτάνει από μικρόφωνο, όχι από πληκτρολόγιο. Το whisper στα ελληνικά
# μπερδεύει σταθερά «αι/ε», «ει/ι», «η/ι» και τρώει τελικά σύμφωνα — άρα το
# μοντέλο πρέπει να δει «πος κοβο τιμολογιο», όχι μόνο την καθαρή μορφή.
# Ίδιοι κανόνες με το `build_intents.py`: ένα φαινόμενο, μία υλοποίηση.
_NOISE = (
    ("αι", "ε"), ("οι", "ι"), ("ει", "ι"), ("η", "ι"), ("υ", "ι"),
    ("ω", "ο"), ("ν ", " "), ("ς ", " "),
)


def mishear(text: str) -> str:
    out = text
    for _ in range(2):
        old, new = random.choice(_NOISE)
        if old in out:
            out = out.replace(old, new, 1)
    return out


for row in list(rows):
    # Μόνο ελληνικά: τα αγγλικά τα ακούει άλλο μοντέλο-γλώσσα και οι κανόνες
    # θορύβου δεν ισχύουν.
    if random.random() < 0.6 and not row["input"].isascii():
        noisy = mishear(row["input"])
        if noisy != row["input"]:
            rows.append({**row, "input": noisy})

# --- Καθαρισμός ---------------------------------------------------------------
_seen: set[str] = set()
_unique: list[dict[str, str]] = []
for row in rows:
    key = row["input"].strip().lower()
    if key in _seen:
        continue
    _seen.add(key)
    _unique.append(row)
dropped = len(rows) - len(_unique)
rows = _unique
if dropped:
    print("αφαιρέθηκαν {} διπλά".format(dropped))

random.shuffle(rows)
