/**
 * Κείμενο → μορφή έτοιμη για εκφώνηση. Χωρίς μοντέλο, χωρίς megabytes.
 *
 * Ο Piper δεν σκέφτεται: διαβάζει ό,τι του δώσεις. Το «802576637» το βγάζει σαν
 * έναν τεράστιο αριθμό, το «12.100,00 €» σαν «δώδεκα κόμμα εκατό», το «ΑΦΜ» σαν
 * «αφμ», και το «ΕΚΔΟΘΗΚΕ» χωρίς τόνο — γιατί τα ελληνικά κεφαλαία γράφονται
 * άτονα και η μηχανή δεν ξέρει πού πέφτει η έμφαση.
 *
 * Κανόνας ΑΦΜ/ΜΑΡΚ/τηλεφώνου: ανά 2 ψηφία σαν αριθμός· όταν στο τέλος
 * περισσεύει τρίτο ψηφίο, τα τελευταία 3 σαν ένας αριθμός.
 *
 *     802576637 → 80 · 25 · 76 · 637
 *
 * Το κόμμα δεν είναι διακοσμητικό: ο Piper το μεταφράζει σε παύση.
 *
 * ⚠️ ΔΙΔΥΜΟ ΑΡΧΕΙΟ. Η ίδια λογική υπάρχει σε Python
 * (`desktop/src/timologio/etimologio/speakable.py`), γιατί η φωνή καλείται και
 * από τις δύο πλευρές: το `?tts=1` εδώ, το `speech.py` εκεί. Οι δύο υλοποιήσεις
 * ελέγχονται ότι βγάζουν **ακριβώς** το ίδιο κείμενο (`test_speakable.py`) —
 * αλλιώς η ίδια πρόταση θα ακουγόταν αλλιώς στην εφαρμογή υπολογιστή και
 * αλλιώς στον browser. Ό,τι αλλάξει εδώ, αλλάζει και εκεί, στην ίδια συνεδρία.
 */

declare(strict_types=1);

const SPK_ONES = [0 => 'μηδέν', 1 => 'ένα', 2 => 'δύο', 3 => 'τρία',
                  4 => 'τέσσερα', 5 => 'πέντε', 6 => 'έξι', 7 => 'επτά',
                  8 => 'οκτώ', 9 => 'εννέα'];
const SPK_ONES_F = [1 => 'μία', 3 => 'τρεις', 4 => 'τέσσερις'];
const SPK_TEENS = [10 => 'δέκα', 11 => 'έντεκα', 12 => 'δώδεκα',
                   13 => 'δεκατρία', 14 => 'δεκατέσσερα', 15 => 'δεκαπέντε',
                   16 => 'δεκαέξι', 17 => 'δεκαεπτά', 18 => 'δεκαοκτώ',
                   19 => 'δεκαεννέα'];
const SPK_TEENS_F = [13 => 'δεκατρείς', 14 => 'δεκατέσσερις'];
const SPK_TENS = [2 => 'είκοσι', 3 => 'τριάντα', 4 => 'σαράντα', 5 => 'πενήντα',
                  6 => 'εξήντα', 7 => 'εβδομήντα', 8 => 'ογδόντα',
                  9 => 'ενενήντα'];
const SPK_HUNDREDS = [1 => 'εκατόν', 2 => 'διακόσια', 3 => 'τριακόσια',
                      4 => 'τετρακόσια', 5 => 'πεντακόσια', 6 => 'εξακόσια',
                      7 => 'επτακόσια', 8 => 'οκτακόσια', 9 => 'εννιακόσια'];
const SPK_HUNDREDS_F = [1 => 'εκατόν', 2 => 'διακόσιες', 3 => 'τριακόσιες',
                        4 => 'τετρακόσιες', 5 => 'πεντακόσιες', 6 => 'εξακόσιες',
                        7 => 'επτακόσιες', 8 => 'οκτακόσιες', 9 => 'εννιακόσιες'];

const SPK_MONTHS = ['ιανουαρίου', 'φεβρουαρίου', 'μαρτίου', 'απριλίου', 'μαΐου',
                    'ιουνίου', 'ιουλίου', 'αυγούστου', 'σεπτεμβρίου',
                    'οκτωβρίου', 'νοεμβρίου', 'δεκεμβρίου'];

/** Πώς λέγονται τα λατινικά γράμματα του κωδικού χώρας ενός IBAN. */
const SPK_LATIN = ['A' => 'έι', 'B' => 'μπι', 'C' => 'σι', 'D' => 'ντι',
                   'E' => 'ι', 'F' => 'εφ', 'G' => 'τζι', 'H' => 'έιτς',
                   'I' => 'άι', 'J' => 'τζέι', 'K' => 'κέι', 'L' => 'ελ',
                   'M' => 'εμ', 'N' => 'εν', 'O' => 'όου', 'P' => 'πι',
                   'Q' => 'κιου', 'R' => 'αρ', 'S' => 'ες', 'T' => 'τι',
                   'U' => 'γιου', 'V' => 'βι', 'W' => 'ντάμπλιου', 'X' => 'ιξ',
                   'Y' => 'γουάι', 'Z' => 'ζεντ'];

function spk_under_1000(int $n, bool $fem = false): string {
    if ($n === 0) return 'μηδέν';
    $parts = [];
    $h = intdiv($n, 100);
    $rest = $n % 100;
    if ($h) {
        $parts[] = ($h === 1 && $rest === 0)
            ? 'εκατό' : ($fem ? SPK_HUNDREDS_F[$h] : SPK_HUNDREDS[$h]);
    }
    if ($rest) {
        if ($rest < 10) {
            $parts[] = ($fem && isset(SPK_ONES_F[$rest])) ? SPK_ONES_F[$rest] : SPK_ONES[$rest];
        } elseif ($rest < 20) {
            $parts[] = ($fem && isset(SPK_TEENS_F[$rest])) ? SPK_TEENS_F[$rest] : SPK_TEENS[$rest];
        } else {
            $t = intdiv($rest, 10);
            $u = $rest % 10;
            $parts[] = SPK_TENS[$t];
            if ($u) $parts[] = ($fem && isset(SPK_ONES_F[$u])) ? SPK_ONES_F[$u] : SPK_ONES[$u];
        }
    }
    return implode(' ', $parts);
}

/** Ακέραιος σε λέξεις (ως 999.999.999 — αρκεί για ποσά, έτη και πλήθη). */
function spk_number(int $n, bool $fem = false): string {
    if ($n < 0) return 'μείον ' . spk_number(-$n, $fem);
    if ($n < 1000) return spk_under_1000($n, $fem);
    if ($n < 1000000) {
        $th = intdiv($n, 1000);
        $rest = $n % 1000;
        $head = $th === 1 ? ($fem ? 'χίλιες' : 'χίλια')
                          : spk_under_1000($th, true) . ' χιλιάδες';
        return $rest === 0 ? $head : $head . ' ' . spk_under_1000($rest, $fem);
    }
    $mil = intdiv($n, 1000000);
    $rest = $n % 1000000;
    $head = $mil === 1 ? 'ένα εκατομμύριο' : spk_number($mil) . ' εκατομμύρια';
    return $rest === 0 ? $head : $head . ' ' . spk_number($rest, $fem);
}

/** «802576637» → ['80','25','76','637'] (2άδες, τελευταία 3άδα αν περισσέψει). */
function spk_digit_groups(string $code): array {
    $out = [];
    $i = 0;
    $n = strlen($code);
    while ($n - $i > 4) { $out[] = substr($code, $i, 2); $i += 2; }
    $rest = substr($code, $i);
    if (strlen($rest) === 4) { $out[] = substr($rest, 0, 2); $out[] = substr($rest, 2); }
    elseif ($rest !== '') { $out[] = $rest; }
    return $out;
}

function spk_group(string $group): string {
    // Ομάδα που αρχίζει με μηδενικό δεν είναι αριθμός: «05» δεν είναι «πέντε».
    if ($group[0] === '0' && strlen($group) > 1) return spk_digits($group);
    return spk_number((int)$group);
}

/** Ο κωδικός όπως τον λέει άνθρωπος: ομάδες με παύση ανάμεσα. */
function spk_code(string $code): string {
    return implode(', ', array_map('spk_group', spk_digit_groups($code)));
}

function spk_digits(string $code): string {
    $out = [];
    for ($i = 0; $i < strlen($code); $i++) $out[] = SPK_ONES[(int)$code[$i]];
    return implode(' ', $out);
}

/** «2.1» → «δύο τελεία ένα». Τύποι παραστατικών και αριθμοί έκδοσης. */
function spk_dotted(string $code): string {
    $parts = array_map(fn($p) => spk_number((int)$p), explode('.', $code));
    return implode(' τελεία ', $parts);
}

function spk_money(int $euros, int $cents): string {
    $head = $euros === 1 ? 'ένα ευρώ' : spk_number($euros) . ' ευρώ';
    if ($cents === 0) return $head;
    $tail = $cents === 1 ? 'ένα λεπτό' : spk_number($cents) . ' λεπτά';
    return $head . ' και ' . $tail;
}

function spk_percent(int $whole, string $frac = ''): string {
    if ($frac === '') return spk_number($whole) . ' τοις εκατό';
    return spk_number($whole) . ' κόμμα ' . spk_digits($frac) . ' τοις εκατό';
}

function spk_date(int $d, int $m, int $y): string {
    $day = $d === 1 ? 'πρώτη' : spk_number($d);
    return $day . ' ' . SPK_MONTHS[$m - 1] . ' ' . spk_number($y);
}

function spk_time(int $h, int $mi): string {
    if ($mi === 0) return spk_number($h, true) . ' ακριβώς';
    if ($mi === 30) return spk_number($h, true) . ' και μισή';
    return spk_number($h, true) . ' και ' . spk_number($mi);
}

