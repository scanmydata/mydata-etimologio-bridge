/**
 * Το κείμενο όπως πρέπει να ΑΚΟΥΣΤΕΙ.
 *
 * Ό,τι δεν αναγνωρίζεται μένει ως έχει: μια άγνωστη λέξη είναι πάντα καλύτερη
 * από μια λέξη που «διορθώθηκε» λάθος.
 */
function to_speech(string $text): string {
    $out = trim(preg_replace('/\s+/u', ' ', $text) ?? '');
    if ($out === '') return '';

    // 1. Συντομογραφίες, όσο είναι ακόμη κεφαλαίες. Τα μεγαλύτερα κλειδιά
    //    πρώτα, αλλιώς το «ΑΦΜ» θα έτρωγε το «Α.Φ.Μ.».
    foreach ([spk_acronyms(), spk_caps()] as $table) {
        $keys = array_keys($table);
        usort($keys, fn($a, $b) => strlen($b) <=> strlen($a));
        foreach ($keys as $key) {
            $out = preg_replace(
                '/(?<![\p{L}\p{N}])' . preg_quote($key, '/') . '(?![\p{L}\p{N}])/u',
                $table[$key], $out
            ) ?? $out;
        }
    }

    // 2. Αριθμοί, με τη σειρά που δεν αλληλοκαταστρέφονται. Τα ποσά πριν από
    //    τους σκέτους αριθμούς, οι κωδικοί πριν από τα ποσά — αλλιώς το
    //    «12.100,00 €» διαβάζεται ως δύο αριθμοί και το ΑΦΜ ως ένα τεράστιο.
    //
    // ⚠️ Το δεξί σύνορο δεν είναι σκέτο «όχι ψηφίο/τελεία»: η τελεία στο τέλος
    // της πρότασης είναι στίξη, όχι μέρος του αριθμού.
    $end = '(?!\d|[.,]\d)';
    $start = '(?<![\d.,])';

    $out = preg_replace_callback(
        '/\b([A-ZΑ-Ω]{2})(\d[\dA-ZΑ-Ω]{12,30})\b/u',
        function ($m) {
            $country = [];
            foreach (str_split(strtoupper($m[1])) as $ch) {
                $country[] = SPK_LATIN[$ch] ?? strtolower($ch);
            }
            return implode(' ', $country) . ', ' . spk_code(preg_replace('/\D/', '', $m[2]));
        },
        $out
    ) ?? $out;

    $out = preg_replace_callback(
        '/' . $start . '(\d{1,3}(?:\.\d{3})+|\d+)(?:,(\d{1,2}))?\s*(?:€|ευρώ|ευρω|EUR)/u',
        fn($m) => spk_money(
            (int)str_replace('.', '', $m[1]),
            (int)str_pad($m[2] ?? '0', 2, '0', STR_PAD_RIGHT)
        ),
        $out
    ) ?? $out;

    $out = preg_replace_callback(
        '/' . $start . '(\d{1,3})(?:[,.](\d{1,2}))?\s*%/u',
        fn($m) => spk_percent((int)$m[1], $m[2] ?? ''),
        $out
    ) ?? $out;

    $out = preg_replace_callback(
        '/(?<!\d)(\d{1,2})[\/\-.](\d{1,2})[\/\-.](\d{2}|\d{4})(?!\d)/u',
        function ($m) {
            $d = (int)$m[1]; $mo = (int)$m[2]; $y = (int)$m[3];
            if ($y < 100) $y += 2000;
            if ($d < 1 || $d > 31 || $mo < 1 || $mo > 12) return $m[0];
            return spk_date($d, $mo, $y);
        },
        $out
    ) ?? $out;

    $out = preg_replace_callback(
        '/(?<!\d)([01]?\d|2[0-3]):([0-5]\d)(?!\d)/u',
        fn($m) => spk_time((int)$m[1], (int)$m[2]),
        $out
    ) ?? $out;

    // Το κενό μπροστά γίνεται ΚΟΜΜΑ: ο Piper το μεταφράζει σε παύση, και ένας
    // δεκαπενταψήφιος κωδικός χωρίς ανάσα ακούγεται κολλημένος στην προηγούμενη
    // λέξη. Μόνο όταν προηγείται γράμμα ή ψηφίο — όχι μετά από «:» ή «,».
    $out = preg_replace_callback(
        '/((?:(?<=[\p{L}\p{N}])\s)?)' . $start . '(\d{7,})' . $end . '/u',
        fn($m) => ($m[1] !== '' ? ', ' : '') . spk_code($m[2]),
        $out
    ) ?? $out;

    $out = preg_replace_callback(
        '/' . $start . '(\d{1,2}(?:\.\d{1,2}){1,2})' . $end . '/u',
        fn($m) => spk_dotted($m[1]),
        $out
    ) ?? $out;

    $out = preg_replace_callback(
        '/' . $start . '(\d{1,3}(?:\.\d{3})+)' . $end . '/u',
        fn($m) => spk_number((int)str_replace('.', '', $m[1])),
        $out
    ) ?? $out;

    $out = preg_replace_callback(
        '/' . $start . '(\d+),(\d{1,2})' . $end . '/u',
        fn($m) => spk_number((int)$m[1]) . ' κόμμα ' . spk_digits($m[2]),
        $out
    ) ?? $out;

    $out = preg_replace_callback(
        '/(?<![\d.,\p{L}\p{N}_])(\d{1,6})' . $end . '/u',
        fn($m) => spk_number((int)$m[1]),
        $out
    ) ?? $out;

    // 3. Πεζά και καθάρισμα. Τα ελληνικά κεφαλαία γράφονται άτονα, οπότε ο
    //    Piper δεν ξέρει πού πέφτει η έμφαση — η ίδια λέξη πεζή ακούγεται σωστά.
    $out = function_exists('mb_strtolower') ? mb_strtolower($out, 'UTF-8') : strtolower($out);
    // Κρατάμε γράμματα, ψηφία και τα σημεία στίξης που γίνονται παύση.
    $out = preg_replace('/[^\p{L}\p{N}\s.,;:!?\-\/()\']/u', '', $out) ?? $out;
    return trim(preg_replace('/\s+/u', ' ', $out) ?? '');
}
