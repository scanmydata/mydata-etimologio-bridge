def type_label(code: str) -> str:
    """«2.1» → «2.1 Τιμολόγιο Παροχής Υπηρεσιών».

    Άγνωστος κωδικός επιστρέφεται ως έχει, και το κενό γίνεται παύλα: ο πίνακας
    δεν πρέπει ποτέ να δείχνει κενό κελί χωρίς εξήγηση.
    """
    code = (code or "").strip()
    if not code:
        return "—"
    name = INVOICE_TYPE_NAMES.get(code)
    return f"{code} {name}" if name else code


def type_name(code: str) -> str:
    """Μόνο η ονομασία, χωρίς τον κωδικό — για tooltips και αναζήτηση."""
    return INVOICE_TYPE_NAMES.get((code or "").strip(), "")
