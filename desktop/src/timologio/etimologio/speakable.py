#: Ό,τι δεν διαβάζεται: εικονίδια, σύμβολα διεπαφής. Κρατάμε γράμματα, ψηφία
#: και τα σημεία στίξης που ο Piper μεταφράζει σε παύση.
_KEEP = set(".,;:!?-/()'")

# Η σειρά των αντικαταστάσεων ΕΙΝΑΙ η λογική. Τα ποσά πριν από τους σκέτους
# αριθμούς, οι κωδικοί πριν από τα ποσά — αλλιώς το «12.100,00 €» θα διαβαστεί
# ως δύο αριθμοί και το ΑΦΜ ως ένα τεράστιο νούμερο.
# ⚠️ Το δεξί σύνορο ΔΕΝ είναι σκέτο `(?![\d.,])`: η τελεία στο τέλος της
# πρότασης είναι στίξη, όχι μέρος του αριθμού. Με το παλιό σύνορο, το
# «ΜΑΡΚ 400000123456789.» δεν αναγνωριζόταν καθόλου — μόνο και μόνο επειδή
# τελείωνε η πρόταση.
_END = r"(?!\d|[.,]\d)"
_START = r"(?<![\d.,])"

_MONEY = re.compile(_START + r"(\d{1,3}(?:\.\d{3})+|\d+)(?:,(\d{1,2}))?\s*(?:€|ευρώ|ευρω|EUR)")
_PERCENT = re.compile(_START + r"(\d{1,3})(?:[,.](\d{1,2}))?\s*%")
_DATE = re.compile(r"(?<!\d)(\d{1,2})[/\-.](\d{1,2})[/\-.](\d{2}|\d{4})(?!\d)")
_TIME = re.compile(r"(?<!\d)([01]?\d|2[0-3]):([0-5]\d)(?!\d)")
_IBAN = re.compile(r"\b([A-ZΑ-Ω]{2})(\d[\dA-ZΑ-Ω]{12,30})\b")
# Το κενό μπροστά μπαίνει στο ταίριασμα ώστε να γίνει **κόμμα**: ο Piper το
# μεταφράζει σε παύση, και ένας δεκαπενταψήφιος κωδικός χωρίς ανάσα μπροστά
# ακούγεται κολλημένος στην προηγούμενη λέξη.
_CODE = re.compile(r"((?:(?<=\w)\s)?)" + _START + r"(\d{7,})" + _END)
_DOTTED = re.compile(_START + r"(\d{1,2}(?:\.\d{1,2}){1,2})" + _END)
_THOUSANDS = re.compile(_START + r"(\d{1,3}(?:\.\d{3})+)" + _END)
_DECIMAL = re.compile(_START + r"(\d+),(\d{1,2})" + _END)
_PLAIN = re.compile(r"(?<![\d.,\w])(\d{1,6})" + _END)


def _money_sub(m: re.Match[str]) -> str:
    euros = int(m.group(1).replace(".", ""))
    cents = int((m.group(2) or "0").ljust(2, "0"))
    return money(euros, cents)


def _percent_sub(m: re.Match[str]) -> str:
    return percent(int(m.group(1)), m.group(2) or "")


#: Πώς λέγονται τα λατινικά γράμματα του κωδικού χώρας ενός IBAN.
_LATIN = {"A": "έι", "B": "μπι", "C": "σι", "D": "ντι", "E": "ι", "F": "εφ",
          "G": "τζι", "H": "έιτς", "I": "άι", "J": "τζέι", "K": "κέι",
          "L": "ελ", "M": "εμ", "N": "εν", "O": "όου", "P": "πι", "Q": "κιου",
          "R": "αρ", "S": "ες", "T": "τι", "U": "γιου", "V": "βι",
          "W": "ντάμπλιου", "X": "ιξ", "Y": "γουάι", "Z": "ζεντ"}


def _iban_sub(m: "re.Match[str]") -> str:
    country = " ".join(_LATIN.get(ch, ch.lower()) for ch in m.group(1).upper())
    return country + ", " + say_code(re.sub(r"\D", "", m.group(2)))


def _date_sub(m: re.Match[str]) -> str:
    day, month = int(m.group(1)), int(m.group(2))
    year = int(m.group(3))
    if year < 100:
        year += 2000
    if not (1 <= day <= 31 and 1 <= month <= 12):
        return m.group(0)
    return say_date(day, month, year)


def to_speech(text: str) -> str:
    """Το κείμενο όπως πρέπει να **ακουστεί**.

    Ό,τι δεν αναγνωρίζεται μένει ως έχει: μια άγνωστη λέξη είναι πάντα καλύτερη
    από μια λέξη που «διορθώθηκε» λάθος.
    """
    out = " ".join(str(text or "").split())
    if not out:
        return ""

    # 1. Συντομογραφίες, όσο είναι ακόμη κεφαλαίες.
    for key in sorted(ACRONYMS, key=len, reverse=True):
        out = re.sub(r"(?<![\wΑ-Ωα-ω])" + re.escape(key) + r"(?![\wΑ-Ωα-ω])",
                     ACRONYMS[key], out)
    for key in sorted(CAPS, key=len, reverse=True):
        out = re.sub(r"(?<![\wΑ-Ωα-ω])" + re.escape(key) + r"(?![\wΑ-Ωα-ω])",
                     CAPS[key], out)

    # 2. Αριθμοί, με τη σειρά που δεν αλληλοκαταστρέφονται.
    out = _IBAN.sub(_iban_sub, out)
    out = _MONEY.sub(_money_sub, out)
    out = _PERCENT.sub(_percent_sub, out)
    out = _DATE.sub(_date_sub, out)
    out = _TIME.sub(lambda m: say_time(int(m.group(1)), int(m.group(2))), out)
    out = _CODE.sub(
        lambda m: (", " if m.group(1) else "") + say_code(m.group(2)), out)
    out = _DOTTED.sub(lambda m: say_dotted(m.group(1)), out)
    out = _THOUSANDS.sub(lambda m: number(int(m.group(1).replace(".", ""))), out)
    out = _DECIMAL.sub(
        lambda m: number(int(m.group(1))) + " κόμμα " + say_digits(m.group(2)), out)
    out = _PLAIN.sub(lambda m: number(int(m.group(1))), out)

    # 3. Πεζά και καθάρισμα. Τα ελληνικά κεφαλαία γράφονται άτονα, οπότε ο Piper
    #    δεν ξέρει πού πέφτει η έμφαση — η ίδια λέξη πεζή ακούγεται σωστά.
    out = out.lower()
    out = "".join(ch for ch in out
                  if ch.isalnum() or ch.isspace() or ch in _KEEP)
    return " ".join(out.split()).strip()
