"""Κείμενο → μορφή έτοιμη για εκφώνηση. Χωρίς μοντέλο, χωρίς megabytes.

Ο Piper δεν σκέφτεται: διαβάζει ό,τι του δώσεις. Το «802576637» το βγάζει σαν
έναν τεράστιο αριθμό, το «12.100,00 €» σαν «δώδεκα κόμμα εκατό», το «ΑΦΜ» σαν
«αφμ», και το «ΕΚΔΟΘΗΚΕ» χωρίς τόνο — γιατί τα ελληνικά κεφαλαία γράφονται
άτονα και η μηχανή δεν ξέρει πού πέφτει η έμφαση.

Αυτό το αρχείο μπαίνει **ανάμεσα** στην απάντηση του βοηθού και τον Piper:

    απάντηση ─► to_speech() ─► «αφιμί, ογδόντα, είκοσι πέντε, …» ─► Piper

Κανόνας ΑΦΜ/ΜΑΡΚ/τηλεφώνου: **ανά 2 ψηφία σαν αριθμός· όταν στο τέλος
περισσεύει τρίτο ψηφίο, τα τελευταία 3 σαν ένας αριθμός.**

    802576637 → 80 · 25 · 76 · 637
              → «ογδόντα, είκοσι πέντε, εβδομήντα έξι, εξακόσια τριάντα επτά»

Το κόμμα δεν είναι διακοσμητικό: ο Piper το μεταφράζει σε παύση.

⚠️ **Δίδυμο αρχείο.** Η ίδια λογική υπάρχει σε PHP (`speakable.php`), γιατί η
φωνή καλείται και από τις δύο πλευρές. Οι δύο υλοποιήσεις ελέγχονται ότι
βγάζουν **ακριβώς** το ίδιο κείμενο (`test_speakable.py`) — αλλιώς η ίδια
πρόταση θα ακουγόταν αλλιώς στην εφαρμογή υπολογιστή και αλλιώς στον browser.
"""

