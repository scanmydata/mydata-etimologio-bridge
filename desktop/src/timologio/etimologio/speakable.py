def _under_1000(n: int, fem: bool = False) -> str:
    if n == 0:
        return "μηδέν"
    parts: list[str] = []
    h, rest = divmod(n, 100)
    if h:
        parts.append("εκατό" if (h == 1 and rest == 0)
                     else (HUNDREDS_F if fem else HUNDREDS)[h])
    if rest:
        if rest < 10:
            parts.append((ONES_F if fem else {}).get(rest) or ONES[rest])
        elif rest < 20:
            parts.append((TEENS_F if fem else {}).get(rest) or TEENS[rest])
        else:
            t, u = divmod(rest, 10)
            parts.append(TENS[t])
            if u:
                parts.append((ONES_F if fem else {}).get(u) or ONES[u])
    return " ".join(parts)


def number(n: int, fem: bool = False) -> str:
    """Ακέραιος σε λέξεις (ως 999.999.999 — αρκεί για ποσά, έτη και πλήθη)."""
    if n < 0:
        return "μείον " + number(-n, fem)
    if n < 1000:
        return _under_1000(n, fem)
    if n < 1_000_000:
        th, rest = divmod(n, 1000)
        head = ("χίλιες" if fem else "χίλια") if th == 1 \
            else _under_1000(th, fem=True) + " χιλιάδες"
        return head if rest == 0 else head + " " + _under_1000(rest, fem)
    mil, rest = divmod(n, 1_000_000)
    head = "ένα εκατομμύριο" if mil == 1 else number(mil) + " εκατομμύρια"
    return head if rest == 0 else head + " " + number(rest, fem)


# --- Ο κανόνας των ψηφίων ------------------------------------------------------

def digit_groups(code: str) -> list[str]:
    """«802576637» → ['80','25','76','637'] (2άδες, τελευταία 3άδα αν περισσέψει)."""
    out: list[str] = []
    i, n = 0, len(code)
    while n - i > 4:
        out.append(code[i:i + 2])
        i += 2
    rest = code[i:]
    if len(rest) == 4:
        out += [rest[:2], rest[2:]]
    elif rest:
        out.append(rest)
    return out


def say_group(group: str) -> str:
    # Ομάδα που αρχίζει με μηδενικό δεν είναι αριθμός: «05» δεν είναι «πέντε».
    if group.startswith("0") and len(group) > 1:
        return " ".join(ONES[int(d)] for d in group)
    return number(int(group))


def say_code(code: str) -> str:
    """Ο κωδικός όπως τον λέει άνθρωπος: ομάδες με παύση ανάμεσα."""
    return ", ".join(say_group(g) for g in digit_groups(code))


def say_digits(code: str) -> str:
    return " ".join(ONES[int(d)] for d in code)


def say_dotted(code: str) -> str:
    """«2.1» → «δύο τελεία ένα». Τύποι παραστατικών και αριθμοί έκδοσης.

    ΔΕΝ είναι αριθμός: το «11.2» δεν είναι «έντεκα κόμμα δύο» — είναι δύο
    ξεχωριστά νούμερα με τελεία ανάμεσα, όπως το λέει ο λογιστής.
    """
    return " τελεία ".join(number(int(p)) for p in code.split("."))


def money(euros: int, cents: int) -> str:
    head = "ένα ευρώ" if euros == 1 else number(euros) + " ευρώ"
    if cents == 0:
        return head
    tail = "ένα λεπτό" if cents == 1 else number(cents) + " λεπτά"
    return head + " και " + tail


def percent(whole: int, frac: str = "") -> str:
    if not frac:
        return number(whole) + " τοις εκατό"
    return number(whole) + " κόμμα " + say_digits(frac) + " τοις εκατό"


MONTHS = ["ιανουαρίου", "φεβρουαρίου", "μαρτίου", "απριλίου", "μαΐου",
          "ιουνίου", "ιουλίου", "αυγούστου", "σεπτεμβρίου", "οκτωβρίου",
          "νοεμβρίου", "δεκεμβρίου"]


def say_date(d: int, m: int, y: int) -> str:
    day = "πρώτη" if d == 1 else number(d)
    return day + " " + MONTHS[m - 1] + " " + number(y)


def say_time(h: int, mi: int) -> str:
    if mi == 0:
        return number(h, fem=True) + " ακριβώς"
    if mi == 30:
        return number(h, fem=True) + " και μισή"
    return number(h, fem=True) + " και " + number(mi)


