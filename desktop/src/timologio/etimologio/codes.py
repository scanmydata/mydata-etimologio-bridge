"""Τα σταθερά λεξιλόγια της ΑΑΔΕ που μοιράζονται οι σελίδες.

Ζούσαν διάσπαρτα: ο πίνακας μεθόδων πληρωμής υπήρχε **δύο φορές** (στην Έκδοση
ως λίστα και στην Καρτέλα ως λεξικό) με διαφορετικές ετικέτες και διαφορετική
σειρά — οπότε η προεπιλογή της κάθε σελίδας ήταν ό,τι έτυχε να είναι πρώτο.
Ένας πίνακας εδώ σημαίνει μία προεπιλογή παντού.
"""

from __future__ import annotations

from typing import Any

#: Τύποι παραστατικών εσόδου (κωδικός → ετικέτα) — το υποσύνολο της καθημερινής
#: χρήσης. Η ετικέτα ξεκινά με τον κωδικό myDATA («2.1»), τον οποίο διαβάζει το
#: :func:`series_for_type` για να ταιριάξει τις σειρές.
INVOICE_TYPES: list[tuple[str, str]] = [
    ("20", "2.1 Παροχή Υπηρεσιών"),
    ("1", "1.1 Τιμολόγιο Πώλησης"),
    ("2", "1.2 Πώληση Ενδοκοινοτική"),
    ("3", "1.3 Πώληση Τρίτες Χώρες"),
    ("21", "2.2 Ενδοκοινοτική Παροχή"),
    ("22", "2.3 Παροχή Τρίτων Χωρών"),
    ("30", "3.1 Τίτλος Κτήσης"),
    ("55", "8.1 Ενοίκια / Έσοδο"),
    ("57", "11.1 ΑΛΠ"),
    ("58", "11.2 ΑΠΥ"),
    ("59", "11.3 Απλοποιημένο Τιμολόγιο"),
]

#: Τρόποι πληρωμής (κωδικός ΑΑΔΕ → ετικέτα).
#:
#: **Η σειρά μετράει**: τα combo γεμίζουν με αυτήν τη σειρά, άρα το πρώτο
#: στοιχείο είναι και η προεπιλογή. Το «Επί πιστώσει» μπαίνει πρώτο επειδή αυτό
#: είναι το συνηθισμένο για τιμολόγιο — και είναι η ίδια προεπιλογή που έχει το
#: web (``#iPay`` με ``selected`` στο 5).
PAYMENT_METHODS: list[tuple[int, str]] = [
    (5, "Επί πιστώσει"),
    (3, "Μετρητά"),
    (1, "Επαγγ. λογ. πληρωμών ημεδαπής"),
    (2, "Επαγγ. λογ. πληρωμών αλλοδαπής"),
    (4, "Επιταγή"),
    (6, "Web Banking"),
    (7, "POS / e-POS"),
    (8, "IRIS"),
]

#: Ο κωδικός που πρέπει να προκύπτει όταν ο χρήστης δεν αγγίξει το combo.
DEFAULT_PAYMENT = 5

#: Αναζήτηση ετικέτας από κωδικό, για πίνακες που δείχνουν αποθηκευμένες κινήσεις.
PAYMENT_LABELS: dict[str, str] = {str(code): label for code, label in PAYMENT_METHODS}

#: Οι μέθοδοι που δέχεται μια *πληρωμή* (είσπραξη) — «επί πιστώσει» δεν είναι
#: είσπραξη, οπότε δεν εμφανίζεται εκεί.
PAYMENT_METHODS_CASH: list[tuple[int, str]] = [
    (3, "Μετρητά"),
    (1, "Επαγγ. λογ. πληρωμών ημεδαπής"),
    (4, "Επιταγή"),
    (6, "Web Banking"),
    (7, "POS / e-POS"),
    (8, "IRIS"),
]

VAT_RATES = ["24", "13", "6", "0"]


def type_label(code: str) -> str:
    return dict(INVOICE_TYPES).get(str(code), "")


def series_for_type(all_series: list[dict[str, Any]], type_code: str) -> list[dict[str, Any]]:
    """Οι σειρές που ανήκουν στον συγκεκριμένο τύπο παραστατικού.

    Το backend επιστρέφει τον τύπο μιας σειράς ως «2.1 - Τιμολόγιο…»· ταιριάζουμε
    με τον αριθμητικό πρόθεμα («2.1») που υπάρχει και στη δική μας ετικέτα. Χωρίς
    αυτό το φιλτράρισμα η ΑΑΔΕ απορρίπτει την έκδοση στο τέλος — αφού ο χρήστης
    έχει συμπληρώσει ολόκληρο το παραστατικό (ή ολόκληρη την παρτίδα).
    """
    dotted = type_label(type_code).split(" ", 1)[0]
    if not dotted:
        return []
    return [
        s for s in all_series
        if str(s.get("invoice_type", "")).strip().startswith(dotted)
    ]
